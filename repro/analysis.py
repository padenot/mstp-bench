"""Analyze one trial directory (see trial.py) into analysis.json.

All positions are source frames: observed streams are resampled to the
source's rate before matching. All times are wall-clock milliseconds.

  backlog   How much generated source audio has not yet left the DSP, sampled
            about every 10 ms of output. After each stall: how long until the
            backlog returns to its pre-stall level.
  playout   Age of the source audio the receiver is playing, per 100 ms, using
            getOutputTimestamp() to time when it reaches the output device.
  jitter    The receiver's jitter buffer, from getStats().
  dsp       Time spent in DSP per second of audio, per phase.
  recording Content and timeline checks of sender.webm (recording.py).
"""
import json
from pathlib import Path

import numpy as np

from . import recording
from .matching import WINDOW_MS, bandpass, frames, match, resample
from .signal import expected

SETTLE_S = 1.5  # Ignore the first 1.5 s after the source starts.
END_S = 0.2     # ...and the last 0.2 s.
CLOCK_RESOLUTION_MS = 1  # Firefox AudioWorklet timestamps are whole milliseconds.


class Trial:
    def __init__(self, directory: Path):
        self.directory = directory
        self.meta = json.loads((directory / "trial.json").read_text())
        self.sender = json.loads((directory / "sender.json").read_text())
        self.receiver = json.loads((directory / "receiver.json").read_text())
        self.config = self.sender["config"]
        self.rate = self.sender["rates"]["source"]
        self.start = self.config["startWallMs"]
        self.duration = self.config["durationSeconds"]
        # [frame, frames, wallMs] for every block the source generated.
        self.source = np.array(self.sender["source_blocks"])
        assert np.all(np.diff(self.source[:, 0]) == self.source[:-1, 1]), "Source blocks are not contiguous"
        self.stalls = list(zip(self.events("stall_start"), self.events("stall_end")))
        assert len(self.stalls) == len(self.config["stalls"]), "Not every requested stall happened"

    def events(self, kind):
        return [e for e in self.sender["events"] if e["type"] == kind]

    def samples(self, name, rate):
        return resample(np.fromfile(self.directory / name, dtype="<f4").astype(np.float64), rate, self.rate)

    def template(self, extra_s=2):
        count = int(self.source[-1, 0] + extra_s * self.rate)
        return bandpass(expected(count, self.rate, self.config["dsp"]), self.rate)

    def generated(self, wall, resolution_ms=0.0):
        """Source frames generated by `wall`, as [lower, upper] bounds when timestamps tie."""
        ends = self.source[:, 0] + self.source[:, 1]
        lo = np.searchsorted(self.source[:, 2], wall - resolution_ms, side="left") - 1
        hi = np.searchsorted(self.source[:, 2], wall + resolution_ms, side="right") - 1
        return [float(ends[i]) if i >= 0 else 0.0 for i in (lo, hi)]

    def source_wall(self, frame):
        return float(np.interp(frame, self.source[:, 0], self.source[:, 2]))

    def inside(self, wall):
        return self.start + SETTLE_S * 1000 <= wall <= self.start + (self.duration - END_S) * 1000


def backlog(t: Trial) -> dict:
    """Generated source audio not yet processed, at the DSP output."""
    pcm = bandpass(t.samples("sender-output.f32", t.sender["rates"]["processing"]), t.rate)
    template, n = t.template(), frames(WINDOW_MS, t.rate)
    blocks = np.array(t.sender["output_blocks"])  # [offset, frames, wallMs]
    scale = t.rate / t.sender["rates"]["processing"]
    # The worker path is observed after its output ring, which keeps draining
    # processed audio while the worker stalls; its peak is at the stall's end.
    buffered = t.config["path"] == "worker"

    # Sample about every 10 ms of output, plus the last block before each peak.
    selected, last, spacing = set(), -np.inf, frames(10, t.sender["rates"]["processing"])
    for i, offset in enumerate(blocks[:, 0]):
        if offset - last >= spacing:
            selected.add(i)
            last = offset
    for begin, end in t.stalls:
        anchor = (end if buffered else begin)["wallMs"]
        selected.add(int(np.searchsorted(blocks[:, 2], anchor + 1, side="right")) - 1)

    points, rejected = [], 0
    for i in sorted(selected):
        end_frame = int(round((blocks[i, 0] + blocks[i, 1]) * scale))
        wall = blocks[i, 2]
        if end_frame < n or not t.inside(wall):
            continue
        generated = t.generated(wall, CLOCK_RESOLUTION_MS)
        m = match(template, pcm[end_frame - n:end_frame], generated[0] - 1.5 * t.rate, generated[1] + n, t.rate)
        if not m.accepted:
            rejected += 1
            continue
        processed = m.center + n / 2
        points.append({"wallMs": wall, "processedFrame": processed,
                       "unprocessedMs": [(g - processed) * 1000 / t.rate for g in generated]})

    first_stall = t.stalls[0][0]["wallMs"] if t.stalls else np.inf
    baseline = [p["unprocessedMs"][1] for p in points if p["wallMs"] < first_stall]
    assert baseline, "No backlog observations before the first stall"
    p95 = float(np.percentile(baseline, 95))
    # The source delivers in batches; one batch of slack separates "back to
    # normal" from noise at a batch boundary.
    walls = np.unique(t.source[(t.source[:, 2] >= t.start + SETTLE_S * 1000) & (t.source[:, 2] < first_stall), 2])
    batch_ms = max((hi - lo) * 1000 / t.rate for lo, hi in (t.generated(w) for w in walls))

    stalls = []
    for index, (begin, end) in enumerate(t.stalls):
        before = [p for p in points if p["wallMs"] <= (end if buffered else begin)["wallMs"] + 1]
        assert buffered or not any(begin["wallMs"] + 1 < b < end["wallMs"] - 1 for b in blocks[:, 2]), \
            "Processing output advanced during a deliberate stall"
        peak = [(g - before[-1]["processedFrame"]) * 1000 / t.rate for g in t.generated(end["wallMs"], CLOCK_RESOLUTION_MS)]
        cutoff = t.stalls[index + 1][0]["wallMs"] if index + 1 < len(t.stalls) else np.inf
        stalls.append({"durationMs": end["durationMs"], "startWallMs": begin["wallMs"], "endWallMs": end["wallMs"],
                       "peakUnprocessedMs": peak,
                       "recovery": {f"{k}Batches": recovery(points, end["wallMs"], cutoff, p95 + k * batch_ms)
                                    for k in (0, 1, 2)}})
    return {"baselineP95Ms": p95, "batchMs": batch_ms, "matched": len(points), "rejected": rejected,
            "stalls": stalls, "points": points}


def recovery(points, end, cutoff, ceiling, follow_ms=500):
    """First return under `ceiling` after `end`, and the first that stays under
    it for at least `follow_ms` of observations."""
    after = [p for p in points if end <= p["wallMs"] < cutoff]
    under = [p["unprocessedMs"][1] <= ceiling for p in after]
    first = next((p["wallMs"] - end for p, ok in zip(after, under) if ok), None)
    sustained = None
    for i, point in enumerate(after):
        j = next((j for j in range(i, len(after)) if after[j]["wallMs"] >= point["wallMs"] + follow_ms), None)
        if j is None:
            break
        if all(under[i:j + 1]):
            sustained = point["wallMs"] - end
            break
    return {"ceilingMs": ceiling, "firstMs": first, "sustainedMs": sustained}


def output_clock(t: Trial):
    """Map a receiver context frame to when it reaches the output device."""
    clocks = [c for c in t.receiver["clocks"] if c["contextTime"] > 0 and c["performanceTime"] > 0]
    times = np.array([c["contextTime"] for c in clocks])
    assert len(clocks) >= 2 and np.all(np.diff(times) > 0), "No usable getOutputTimestamp() observations"
    rate, origin = t.receiver["rates"]["playout"], t.receiver["timeOrigin"]

    def device_wall(frame):
        seconds = frame / rate
        i = int(np.argmin(np.abs(times - seconds)))
        assert abs(times[i] - seconds) <= 0.5, "Output clock observation too distant"
        return origin + clocks[i]["performanceTime"] + (seconds - times[i]) * 1000
    return device_wall


def playout(t: Trial, hop_ms=100) -> list[dict]:
    """Source age of what the receiver plays, at the output device."""
    rate = t.receiver["rates"]["playout"]
    pcm = bandpass(t.samples("receiver-playout.f32", rate), t.rate)
    blocks = np.array(t.receiver["playout_blocks"])  # [contextFrame, frames, wallMs]
    offsets = np.r_[0, np.cumsum(blocks[:-1, 1])] * t.rate / rate
    template, n, device_wall = t.template(), frames(WINDOW_MS, t.rate), output_clock(t)
    windows = []
    for offset in range(0, len(pcm) - n, frames(hop_ms, t.rate)):
        center = offset + n // 2
        wall = device_wall(np.interp(center, offsets, blocks[:, 0]))
        if not t.inside(wall):
            continue
        now = t.generated(wall)[1]
        m = match(template, pcm[offset:offset + n], now - 1.5 * t.rate, now + n, t.rate)
        windows.append({"wallMs": wall, "accepted": m.accepted,
                        "sourceAgeMs": wall - t.source_wall(m.center) if m.accepted else None})
    return windows


def jitter_buffer(t: Trial) -> list[dict]:
    """Per-interval averages from consecutive inbound-rtp getStats() reports."""
    intervals, previous = [], None
    for sample in t.receiver["stats"]:
        report = next((r for r in sample["reports"] if r.get("kind") == "audio"), None)
        if report is None:
            continue
        if previous and report.get("totalSamplesDuration"):
            # Sample counters run at the decoder's rate.
            rate = report["totalSamplesReceived"] / report["totalSamplesDuration"]
            emitted = report["jitterBufferEmittedCount"] - previous["jitterBufferEmittedCount"]

            def per(key, scale):
                if key not in report or key not in previous or not scale:
                    return None
                return (report[key] - previous[key]) * 1000 / scale
            intervals.append({
                "wallMs": sample["wallMs"],
                "delayMs": per("jitterBufferDelay", emitted),
                "targetMs": per("jitterBufferTargetDelay", emitted),
                "acceleratedMs": per("removedSamplesForAcceleration", rate),
                "concealedMs": per("concealedSamples", rate),
            })
        previous = report
    return intervals


def phases(t: Trial) -> dict:
    """Named [from, to) intervals in seconds after the source starts."""
    load = t.config.get("load")
    if not load:
        first = min([s["atSeconds"] for s in t.config["stalls"]], default=t.duration - END_S)
        return {"beforeStalls": (SETTLE_S, first)}
    on, off = load["atSeconds"], load["atSeconds"] + load["seconds"]
    # One second of transition is excluded around each load change.
    return {"before": (SETTLE_S, on), "load": (on + 1, off), "after": (off + 2, t.duration - END_S)}


def dsp_cost(t: Trial, span) -> float | None:
    """DSP milliseconds per second of processed audio within `span`."""
    progress = [e for e in t.events("progress")
                if t.start + span[0] * 1000 <= e["wallMs"] < t.start + span[1] * 1000]
    if len(progress) < 2:
        return None
    a, b = progress[0], progress[-1]
    return (b["dspMs"] - a["dspMs"]) / ((b["processedFrames"] - a["processedFrames"]) / t.sender["rates"]["processing"])


def analyze(directory: Path) -> dict:
    t = Trial(directory)
    start = next(e["wallMs"] for e in t.events("recording_start"))
    result = {
        "config": t.config, "browser": t.meta["browser"], "rates": {**t.sender["rates"], **t.receiver["rates"]},
        "recording": recording.check(directory / "sender.webm", t.rate, t.duration, t.config["dsp"],
                                     prefix=(t.start - start) * t.rate / 1000),
        "backlog": backlog(t), "playout": playout(t), "jitterBuffer": jitter_buffer(t),
        "phases": {name: {"seconds": span, "dspMsPerSecond": dsp_cost(t, span)} for name, span in phases(t).items()},
        "sourceMaxGapMs": float(np.diff(t.source[:, 2]).max()),
    }
    (directory / "analysis.json").write_text(json.dumps(result, indent=2, default=lambda value: value.item()))  # NumPy scalars
    return result
